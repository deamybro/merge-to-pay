// Emit circuit/src/template.nr from src/spec.mjs: the constant claim pieces as byte arrays, plus the
// keccak sponge state after absorbing every full 136-byte block of the constant head (the midstate).
// Usage: node scripts/gen-circuit.mjs            (writes the file)
//        node scripts/gen-circuit.mjs --stdout   (prints it; the test diffs this against disk)
import { writeFileSync } from 'node:fs'
import { keccakP } from '@noble/hashes/sha3'
import { u32 } from '@noble/hashes/utils'
import { template } from '../src/spec.mjs'

export const RATE = 136

/** Sponge state (25 little-endian u64 lanes) after absorbing `blocks` full blocks of `bytes`. */
export function midstate(bytes, blocks) {
  const st = new Uint8Array(200)
  for (let b = 0; b < blocks; b++) {
    for (let i = 0; i < RATE; i++) st[i] ^= bytes[b * RATE + i]
    keccakP(u32(st), 24)
  }
  const view = new DataView(st.buffer)
  return Array.from({ length: 25 }, (_, l) => view.getBigUint64(l * 8, true))
}

export function render() {
  const t = template()
  const head = Buffer.from(t.head)
  const blocks = Math.floor(head.length / RATE)
  const rest = head.subarray(blocks * RATE)
  const arr = (name, buf) => `pub global ${name}: [u8; ${buf.length}] = [${Array.from(buf).join(', ')}];`
  return [
    '// GENERATED by scripts/gen-circuit.mjs from src/spec.mjs. Do not edit.',
    `// HEAD is ${head.length} bytes: ${blocks} full keccak blocks absorbed here, ${rest.length} bytes left for the circuit.`,
    `pub global HEAD_BLOCKS: u32 = ${blocks};`,
    `pub global MIDSTATE: [u64; 25] = [${midstate(head, blocks).map((v) => '0x' + v.toString(16)).join(', ')}];`,
    arr('HEAD_REST', rest),
    arr('ISSUES', Buffer.from(t.issues)),
    arr('MID', Buffer.from(t.mid)),
    arr('CTX_ISSUE', Buffer.from(t.ctx.issue)),
    arr('CTX_MERGED_AT_AFTER_ISSUE', Buffer.from(t.ctx.mergedAtAfterIssue)),
    arr('CTX_MERGED_AT', Buffer.from(t.ctx.mergedAt)),
    arr('CTX_PAYEE', Buffer.from(t.ctx.payee)),
    arr('CTX_PROVIDER_HASH', Buffer.from(t.ctx.providerHash)),
    arr('TAIL', Buffer.from(t.tail)),
    '',
  ].join('\n')
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const out = render()
  if (process.argv.includes('--stdout')) process.stdout.write(out)
  else writeFileSync(new URL('../circuit/src/template.nr', import.meta.url), out)
}
